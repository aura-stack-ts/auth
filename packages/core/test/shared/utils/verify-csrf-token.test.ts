import { describe, test, expect } from "vitest"
import { getEnv } from "@/shared/utils/get-env.ts"
import { jose } from "@test/setup/auth.ts"
import { signJWS } from "@aura-stack/jose"
import { createCSRF } from "@/exports/crypto.ts"
import { createContext } from "@/config/context.ts"
import { AuraAuthError } from "@/shared/errors/aura-error.ts"
import {
    assertCSRFToken,
    verifyDoubleSubmitCSRFToken,
    verifyDoubleSubmitCSRFTokenFromRequest,
} from "@/shared/utils/verify-csrf-token.ts"

describe("assertCSRFToken", () => {
    test("rejects an empty token as invalid", async () => {
        await expect(assertCSRFToken(jose, "invalid-jws")).rejects.toThrow(new AuraAuthError({ code: "CSRF_TOKEN_INVALID" }))
    })

    test("accepts a CSRF token generated by the library", async () => {
        const token = await createCSRF(jose)
        expect(await assertCSRFToken(jose, token)).toBe(true)
    })

    test("accepts a valid signed token payload", async () => {
        const token = await jose.signJWS({ token: "value" })
        expect(await assertCSRFToken(jose, token)).toBe(true)
    })

    test("rejects a token signed with a different secret", async () => {
        const secret = getEnv("SECRET")
        const token = await signJWS({ token: "value" }, secret!)
        await expect(assertCSRFToken(jose, token)).rejects.toThrow()
    })

    test("rejects a signed payload without a token value", async () => {
        const token = await jose.signJWS({ name: "non-token" })
        await expect(assertCSRFToken(jose, token)).rejects.toThrow(new AuraAuthError({ code: "CSRF_TOKEN_INVALID_VALUE" }))
    })

    test("rejects an expired token", async () => {
        const token = await jose.signJWS({ exp: Math.floor(Date.now() / 1000) - 3600 })
        await expect(assertCSRFToken(jose, token)).rejects.toThrow(new AuraAuthError({ code: "CSRF_TOKEN_EXPIRED" }))
    })
})

describe("verifyDoubleSubmitCSRFToken", () => {
    test("accepts matching cookie and header tokens", async () => {
        const token = await createCSRF(jose)
        expect(await verifyDoubleSubmitCSRFToken(jose, token, token)).toBe(true)
    })

    test("rejects cookie and header tokens with different values", async () => {
        const cookie = await createCSRF(jose)
        const header = await createCSRF(jose)
        await expect(verifyDoubleSubmitCSRFToken(jose, cookie, header)).rejects.toThrow(
            new AuraAuthError({ code: "CSRF_TOKEN_MISMATCH" })
        )
    })
})

describe("verifyDoubleSubmitCSRFTokenFromRequest", () => {
    test("validates the CSRF cookie against the X-CSRF-Token header", async () => {
        const ctx = createContext({})
        const token = await createCSRF(jose)
        expect(
            await verifyDoubleSubmitCSRFTokenFromRequest({
                ctx,
                cookieStore: ctx.cookies.store,
                headers: new Headers({ Cookie: `__Host-aura-auth.csrf_token=${token}`, "X-CSRF-Token": token }),
                skipCSRFCheck: false,
            })
        ).toBe(true)
    })

    test("uses the supplied CSRF token value when no cookie is present", async () => {
        const ctx = createContext({})
        const token = await createCSRF(jose)
        expect(
            await verifyDoubleSubmitCSRFTokenFromRequest({
                ctx,
                cookieStore: ctx.cookies.store,
                csrfTokenValue: token,
                headers: new Headers({ "X-CSRF-Token": token }),
                skipCSRFCheck: false,
            })
        ).toBe(true)
    })

    test("validates the CSRF cookie against an explicit double-submit token", async () => {
        const ctx = createContext({})
        const token = await createCSRF(jose)
        expect(
            await verifyDoubleSubmitCSRFTokenFromRequest({
                ctx,
                cookieStore: ctx.cookies.store,
                headers: new Headers({ Cookie: `__Host-aura-auth.csrf_token=${token}` }),
                doubleSubmitToken: token,
                skipCSRFCheck: false,
            })
        ).toBe(true)
    })

    test("validates a supplied CSRF token value against an explicit double-submit token", async () => {
        const ctx = createContext({})
        const token = await createCSRF(jose)
        expect(
            await verifyDoubleSubmitCSRFTokenFromRequest({
                ctx,
                cookieStore: ctx.cookies.store,
                csrfTokenValue: token,
                headers: new Headers(),
                doubleSubmitToken: token,
                skipCSRFCheck: false,
            })
        ).toBe(true)
    })

    test("skips the double-submit check when CSRF checking is disabled", async () => {
        const ctx = createContext({})
        const token = await createCSRF(jose)
        expect(
            await verifyDoubleSubmitCSRFTokenFromRequest({
                ctx,
                cookieStore: ctx.cookies.store,
                csrfTokenValue: token,
                headers: new Headers(),
                skipCSRFCheck: true,
            })
        ).toBe(true)
    })

    test("rejects a request without a CSRF cookie or supplied token value", async () => {
        const ctx = createContext({})
        await expect(
            verifyDoubleSubmitCSRFTokenFromRequest({
                ctx,
                cookieStore: ctx.cookies.store,
                headers: new Headers(),
                skipCSRFCheck: false,
                doubleSubmitToken: undefined,
            })
        ).rejects.toThrow(new AuraAuthError({ code: "CSRF_TOKEN_MISSING" }))
    })

    test("rejects a request without a double-submit token when checking is enabled", async () => {
        const ctx = createContext({})
        const token = await createCSRF(jose)
        await expect(
            verifyDoubleSubmitCSRFTokenFromRequest({
                ctx,
                cookieStore: ctx.cookies.store,
                headers: new Headers({ Cookie: `__Host-aura-auth.csrf_token=${token}` }),
                skipCSRFCheck: false,
                doubleSubmitToken: undefined,
            })
        ).rejects.toThrow(new AuraAuthError({ code: "CSRF_DOUBLE_SUBMIT_FAILED" }))
    })

    test("rejects mismatched CSRF cookie and header tokens", async () => {
        const ctx = createContext({})
        const cookie = await createCSRF(jose)
        const header = await createCSRF(jose)
        await expect(
            verifyDoubleSubmitCSRFTokenFromRequest({
                ctx,
                cookieStore: ctx.cookies.store,
                headers: new Headers({ Cookie: `__Host-aura-auth.csrf_token=${cookie}`, "X-CSRF-Token": header }),
                skipCSRFCheck: false,
                doubleSubmitToken: undefined,
            })
        ).rejects.toThrow(new AuraAuthError({ code: "CSRF_TOKEN_MISMATCH" }))
    })

    test("rejects mismatched CSRF cookie and explicit double-submit tokens", async () => {
        const ctx = createContext({})
        const cookie = await createCSRF(jose)
        await expect(
            verifyDoubleSubmitCSRFTokenFromRequest({
                ctx,
                cookieStore: ctx.cookies.store,
                headers: new Headers({ Cookie: `__Host-aura-auth.csrf_token=${cookie}` }),
                skipCSRFCheck: false,
                doubleSubmitToken: "invalid-token-value",
            })
        ).rejects.toThrow(new AuraAuthError({ code: "CSRF_TOKEN_INVALID" }))
    })

    test("rejects mismatched CSRF cookie and explicit double-submit tokens", async () => {
        const ctx = createContext({})
        const cookie = await createCSRF(jose)
        const header = await createCSRF(jose)
        await expect(
            verifyDoubleSubmitCSRFTokenFromRequest({
                ctx,
                cookieStore: ctx.cookies.store,
                headers: new Headers({ Cookie: `__Host-aura-auth.csrf_token=${cookie}` }),
                skipCSRFCheck: false,
                doubleSubmitToken: header,
            })
        ).rejects.toThrow(new AuraAuthError({ code: "CSRF_TOKEN_MISMATCH" }))
    })
})
